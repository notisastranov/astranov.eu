create table if not exists shops (
  id text primary key,
  slug text unique not null,
  name_el text not null,
  name_en text not null,
  trade_el text not null default '',
  trade_en text not null default '',
  address text not null default '',
  city text not null default '',
  postal text not null default '',
  neighborhood text not null default '',
  country text not null default '',
  lat double precision,
  lng double precision,
  rating double precision,
  rating_count integer,
  cuisines_el text not null default '',
  cuisines_en text not null default '',
  hours text not null default '',
  hours_el text not null default '',
  min_order double precision,
  delivery_fee double precision,
  eta_min integer,
  is_open boolean not null default false,
  pickup boolean not null default false,
  pay_card boolean not null default false,
  pay_cash boolean not null default false,
  own_delivery boolean not null default false,
  cover_url text not null default '',
  logo_url text not null default '',
  efood_id integer,
  efood_url text not null default '',
  catalog_as_of text not null default '',
  facts_as_of text not null default '',
  source_note text not null default '',
  updated_at timestamptz not null default now()
);

create table if not exists menu_rows (
  id text primary key,
  shop_id text not null references shops (id),
  sort_index integer not null,
  category_el text not null default '',
  category_en text not null default '',
  name_el text not null default '',
  name_en text not null default '',
  description_el text not null default '',
  description_en text not null default '',
  price double precision,
  price_note_el text not null default '',
  price_note_en text not null default '',
  available boolean not null default true,
  media_url text not null default '',
  media_kind text not null default 'none',
  source_code text not null default '',
  has_options boolean not null default false,
  catalog_text_el text not null default '',
  updated_at timestamptz not null default now()
);

create index if not exists menu_rows_shop_idx on menu_rows (shop_id, sort_index);
